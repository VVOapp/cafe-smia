-- Kampanjer (under Lojalitet-fanen) — kjør dette i Supabase SQL-editoren én gang.
--
-- En kampanje gir lojalitetskunder gratis drikke innenfor gitte dager/klokkeslett,
-- f.eks. "Novemberkos for lærere": én gratis drikk per dag, man–tor før kl. 10:30.
-- Ansatte merker kunden som lærer (én gang) og registrerer valgt drikk i loyalty.html.
-- Læreren ser samtalestarter, bekrefter samtalen og gir tilbakemelding i min-kode.html.
-- Kafeoversikt viser statistikk og kostnad.

-- Lærere merkes av ansatte i skanneren; kun de ser lærerkampanjer på kodesiden sin.
alter table loyalty_customers add column if not exists is_teacher boolean not null default false;

create table if not exists campaigns (
  id                    bigint generated by default as identity primary key,
  name                  text not null,
  description           text,                                   -- vises for kunden i min-kode.html
  start_date            date not null,
  end_date              date not null,
  weekdays              jsonb not null default '[1,2,3,4]'::jsonb, -- JS getDay(): 1=man … 4=tor
  cutoff_time           text not null default '10:30',          -- 'HH:MM', siste klokkeslett tilbudet gjelder
  max_per_day           int  not null default 1,
  teachers_only         boolean not null default true,           -- kun kunder merket som lærer
  product_ids           jsonb not null default '[]'::jsonb,      -- cafe_products.id som kan velges
  conversation_starters jsonb not null default '[]'::jsonb,      -- spørsmål læreren kan stille den ansatte
  active                boolean not null default true,
  created_at            timestamptz default now()
);

create table if not exists campaign_redemptions (
  id                bigint generated by default as identity primary key,
  campaign_id       bigint not null references campaigns(id) on delete cascade,
  customer_id       text not null,                               -- loyalty_customers.id (telefonnummer)
  cafe_product_id   bigint,
  conversation_done boolean,                                     -- bekreftet av læreren i min-kode.html (null = ikke svart)
  drink_rating      smallint check (drink_rating between 1 and 5),
  service_rating    smallint check (service_rating between 1 and 5),
  comment           text,
  feedback_at       timestamptz,
  created_at        timestamptz default now()
);

create index if not exists campaign_redemptions_customer_idx on campaign_redemptions (customer_id, created_at desc);
create index if not exists campaign_redemptions_campaign_idx on campaign_redemptions (campaign_id);

-- RLS: samme mønster som resten av databasen (anon-nøkkelen i appen trenger
-- lese- og skrivetilgang siden det ikke er noen server-backend).
alter table campaigns enable row level security;
create policy "Public access" on campaigns for all using (true) with check (true);
alter table campaign_redemptions enable row level security;
create policy "Public access" on campaign_redemptions for all using (true) with check (true);
